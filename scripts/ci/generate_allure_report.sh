#!/usr/bin/env bash
# CI-only wrapper that merges downloaded `allure-results-*` artifacts, restores
# prior `main` history when publishing to GitHub Pages, writes the GitHub
# Actions Step Summary table, builds the unified Allure 3 report, and emits
# self-hosted SVG metric badges + `metrics.json` for README / Pages.
set -euo pipefail

RAW_DIR="${ALLURE_RAW_DIR:-allure-results-raw}"
MERGED_DIR="${ALLURE_MERGED_DIR:-allure-results}"
REPORT_DIR="${ALLURE_REPORT_DIR:-allure-report}"
CONFIG_FILE="${ALLURE_CONFIG_FILE:-allurerc.json}"
ARTIFACT_NAME="${ALLURE_ARTIFACT_NAME:-allure-report}"
HISTORY_FILE="${ALLURE_HISTORY_FILE:-.allure-history/history.jsonl}"
HISTORY_MAX_ENTRIES="${ALLURE_HISTORY_MAX_ENTRIES:-30}"
PAGES_URL="${ALLURE_PAGES_URL:-}"
REPORT_SCRIPT="${ALLURE_REPORT_SCRIPT:-scripts/allure-report.sh}"

repo_root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$repo_root"

run_url=""
if [ -n "${GITHUB_SERVER_URL:-}" ] && [ -n "${GITHUB_REPOSITORY:-}" ] && [ -n "${GITHUB_RUN_ID:-}" ]; then
  run_url="${GITHUB_SERVER_URL}/${GITHUB_REPOSITORY}/actions/runs/${GITHUB_RUN_ID}"
fi

dashboard_url=""
if [ -n "$PAGES_URL" ]; then
  dashboard_url="${PAGES_URL%/}/"
fi

merge_args=(--output "$MERGED_DIR")
if [ -d "$RAW_DIR" ]; then
  merge_args+=(--input "$RAW_DIR")
else
  rm -rf "$MERGED_DIR"
  mkdir -p "$MERGED_DIR"
fi

[ -n "${GITHUB_REPOSITORY:-}" ] && merge_args+=(--env "Repository=${GITHUB_REPOSITORY}")
[ -n "${GITHUB_REF_NAME:-}" ] && merge_args+=(--env "Ref=${GITHUB_REF_NAME}")
[ -n "${GITHUB_SHA:-}" ] && merge_args+=(--env "Commit=${GITHUB_SHA}")
[ -n "${GITHUB_EVENT_NAME:-}" ] && merge_args+=(--env "Event=${GITHUB_EVENT_NAME}")
[ -n "$run_url" ] && merge_args+=(--env "WorkflowRun=${run_url}")

if [ -n "$run_url" ]; then
  merge_args+=(
    --executor-name "GitHub Actions"
    --executor-type "github"
    --executor-url "${GITHUB_SERVER_URL}/${GITHUB_REPOSITORY}/actions"
    --build-name "${GITHUB_WORKFLOW:-Android CI} #${GITHUB_RUN_NUMBER:-0}"
    --build-url "$run_url"
    --build-order "${GITHUB_RUN_NUMBER:-0}"
  )
fi

if [ -d "$RAW_DIR" ]; then
  python3 scripts/allure_results.py merge "${merge_args[@]}"
fi

result_count="$(find "$MERGED_DIR" -maxdepth 1 -name '*-result.json' | wc -l | tr -d ' ')"

summary_args=(
  --results-dir "$MERGED_DIR"
  --artifact-name "$ARTIFACT_NAME"
)
[ -n "$run_url" ] && summary_args+=(--report-url "$run_url")
[ -n "$dashboard_url" ] && summary_args+=(--dashboard-url "$dashboard_url")
[ -n "${GITHUB_STEP_SUMMARY:-}" ] && summary_args+=(--step-summary "$GITHUB_STEP_SUMMARY")
[ -n "${GITHUB_OUTPUT:-}" ] && summary_args+=(--github-output "$GITHUB_OUTPUT")

python3 scripts/allure_results.py summary "${summary_args[@]}"

if [ "$result_count" -eq 0 ]; then
  echo "No Allure test results found; skipping Allure 3 HTML generation."
  if [ -n "${GITHUB_OUTPUT:-}" ]; then
    echo "has_report=false" >> "$GITHUB_OUTPUT"
  fi
  exit 0
fi

# Restore prior `main` history.jsonl from GitHub Pages so Allure 3 builds
# multi-run trend charts across `main` builds (first deploy starts fresh).
should_fetch_history="${ALLURE_FETCH_HISTORY:-}"
if [ -z "$should_fetch_history" ]; then
  if [ "${GITHUB_REF:-}" = "refs/heads/main" ] \
    && { [ "${GITHUB_EVENT_NAME:-}" = "push" ] || [ "${GITHUB_EVENT_NAME:-}" = "workflow_dispatch" ]; }; then
    should_fetch_history="true"
  else
    should_fetch_history="false"
  fi
fi

mkdir -p "$(dirname "$HISTORY_FILE")"
if [ "$should_fetch_history" = "true" ] && [ -n "$dashboard_url" ]; then
  history_tmp="${HISTORY_FILE}.download"
  if curl -fsSL --max-time 15 "${dashboard_url}history.jsonl" -o "$history_tmp" 2>/dev/null; then
    python3 - "$history_tmp" "$HISTORY_FILE" "$HISTORY_MAX_ENTRIES" <<'PY'
import json
import sys
from pathlib import Path

src, dst, max_entries = Path(sys.argv[1]), Path(sys.argv[2]), int(sys.argv[3])
valid_lines = []
for raw_line in src.read_text(encoding="utf-8", errors="replace").splitlines():
    line = raw_line.strip()
    if not line:
        continue
    try:
        json.loads(line)
    except ValueError:
        continue
    valid_lines.append(line)
if valid_lines:
    dst.write_text("\n".join(valid_lines[-max_entries:]) + "\n", encoding="utf-8")
PY
    echo "Restored Allure 3 history from ${dashboard_url}history.jsonl"
  else
    echo "No existing Allure 3 history at ${dashboard_url}history.jsonl (starting fresh)."
  fi
  rm -f "$history_tmp"
fi

"$REPORT_SCRIPT" \
  --results-dir "$MERGED_DIR" \
  --output "$REPORT_DIR" \
  --config "$CONFIG_FILE"

if [ ! -f "${REPORT_DIR}/index.html" ]; then
  echo "ERROR: expected ${REPORT_DIR}/index.html to be generated by Allure 3" >&2
  exit 1
fi

# Bundle static site assets for GitHub Pages (history.jsonl, .nojekyll, SVG badges, metrics.json).
: > "${REPORT_DIR}/.nojekyll"

if [ -f "$HISTORY_FILE" ]; then
  tail -n "$HISTORY_MAX_ENTRIES" "$HISTORY_FILE" > "${REPORT_DIR}/history.jsonl"
fi

badge_args=(
  --results-dir "$MERGED_DIR"
  --output-dir "$REPORT_DIR"
)
[ -n "${GITHUB_SHA:-}" ] && badge_args+=(--commit "$GITHUB_SHA")
[ -n "$run_url" ] && badge_args+=(--run-url "$run_url")
[ -n "$dashboard_url" ] && badge_args+=(--dashboard-url "$dashboard_url")

python3 scripts/allure_results.py badges "${badge_args[@]}"

if [ -n "${GITHUB_OUTPUT:-}" ]; then
  echo "has_report=true" >> "$GITHUB_OUTPUT"
fi
